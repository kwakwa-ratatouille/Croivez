// Chaque ligne : [question, réponse, groupe] ; le groupe fournit les mauvaises propositions.
// Rangées de la plus connue à la plus pointue (Facile = le début de la liste). Usage : node scripts/build-defis.mjs
import { writeFile } from 'node:fs/promises'

const ecrire = (id, lignes) => {
  const items = lignes.map(([q, r, g], i) => ({ id: `${id}-${i}`, n: { fr: q, en: q }, r: { fr: r, en: r }, g }))
  return writeFile(`public/packs/culture/${id}.json`, JSON.stringify(items)).then(() => console.log(`${id} : ${items.length}`))
}

